import os
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)


def export_pdf(proposal, filename):

    output_folder = "generated_proposals"

    os.makedirs(output_folder, exist_ok=True)

    pdf_path = os.path.join(
        output_folder,
        filename + ".pdf"
    )

    doc = SimpleDocTemplate(pdf_path)

    styles = getSampleStyleSheet()

    elements = []

    # --------------------------------
    # Title
    # --------------------------------

    title = Paragraph(
        "<b><font size=20>AI Generated Software Proposal</font></b>",
        styles["Title"]
    )

    elements.append(title)
    elements.append(Spacer(1, 20))

    # --------------------------------
    # Information Table
    # --------------------------------

    data = [

        ["Generated By", "AI Proposal Automation"],

        ["Prepared By", "Harshit Goyal"],

        ["Date", datetime.now().strftime("%d-%m-%Y")]

    ]

    table = Table(data)

    table.setStyle(

        TableStyle([

            ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),

            ("GRID", (0, 0), (-1, -1), 1, colors.black),

            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),

            ("TOPPADDING", (0, 0), (-1, -1), 8),

        ])

    )

    elements.append(table)

    elements.append(Spacer(1, 20))

    # --------------------------------
    # Proposal
    # --------------------------------

    for line in proposal.split("\n"):

        line = line.strip()

        if not line:
            continue

        if line.startswith("#"):

            elements.append(

                Paragraph(

                    f"<b>{line.replace('#','')}</b>",

                    styles["Heading2"]

                )

            )

        else:

            elements.append(

                Paragraph(

                    line,

                    styles["BodyText"]

                )

            )

        elements.append(Spacer(1, 6))

    # --------------------------------

    doc.build(elements)

    return pdf_path