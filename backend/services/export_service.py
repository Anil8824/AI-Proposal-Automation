import os
from datetime import datetime

from docx import Document
from docx.shared import Pt
from docx.enum.text import WD_PARAGRAPH_ALIGNMENT


def export_proposal(proposal, filename):

    output_folder = "generated_proposals"
    os.makedirs(output_folder, exist_ok=True)

    document = Document()

    # ----------------------------
    # Cover Title
    # ----------------------------

    heading = document.add_heading(level=0)
    heading.alignment = WD_PARAGRAPH_ALIGNMENT.CENTER

    run = heading.add_run("AI GENERATED SOFTWARE PROPOSAL")
    run.font.size = Pt(24)
    run.bold = True

    subtitle = document.add_paragraph()
    subtitle.alignment = WD_PARAGRAPH_ALIGNMENT.CENTER

    subtitle.add_run(
        f"Generated on: {datetime.now().strftime('%d %B %Y')}"
    ).italic = True

    document.add_paragraph()

    # ----------------------------
    # Project Information
    # ----------------------------

    document.add_heading("Project Information", level=1)

    table = document.add_table(rows=4, cols=2)
    table.style = "Table Grid"

    table.cell(0, 0).text = "Generated By"
    table.cell(0, 1).text = "AI Proposal Automation"

    table.cell(1, 0).text = "Prepared For"
    table.cell(1, 1).text = "Client"

    table.cell(2, 0).text = "Prepared By"
    table.cell(2, 1).text = "Harshit Goyal"

    table.cell(3, 0).text = "Date"
    table.cell(3, 1).text = datetime.now().strftime("%d-%m-%Y")

    document.add_page_break()

    # ----------------------------
    # Proposal
    # ----------------------------

    document.add_heading("Software Proposal", level=1)

    for line in proposal.split("\n"):

        line = line.strip()

        if not line:
            continue

        if line.startswith("#"):
            document.add_heading(
                line.replace("#", "").strip(),
                level=2
            )
        else:
            para = document.add_paragraph()
            para.add_run(line).font.size = Pt(11)

    # ----------------------------
    # Footer
    # ----------------------------

    document.add_page_break()

    document.add_heading("End of Proposal", level=2)

    document.add_paragraph(
        "This proposal has been generated automatically using the "
        "AI Proposal Automation System."
    )

    output_path = os.path.join(
        output_folder,
        f"{filename}.docx"
    )

    document.save(output_path)

    return output_path